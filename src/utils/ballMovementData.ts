// Parser to convert formatted strings (like "16-61-72") into numeric ball lists
export function parseNumbers(str: string): number[] {
  if (!str) return [];
  return str
    .split(/[-.]/)
    .map((s) => parseInt(s.trim(), 10))
    .filter((n) => !isNaN(n) && n >= 1 && n <= 90);
}
